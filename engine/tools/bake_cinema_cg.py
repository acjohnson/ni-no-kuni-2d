#!/usr/bin/env python3
"""
Project Hearth — Dual-Target Cinema CG Baker
Converts the 6 master painted anime CG plates into:
  1. engine/platform/cinema_cg_sdl2.h : 340x156 high-color RGB565 plates for Linux/Windows SDL2
  2. engine/platform/cinema_cg_rom.h  : 256x120 (32x15) 16-color indexed 4bpp tilemaps + palettes
                                        (<= 340 unique tiles/plate, split per-plate for SNES LoROM)
Uses ImageMagick `convert` only at bake time; generated C headers have zero runtime dependencies.
"""

import os
import struct
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
IMG_DIR = os.path.join(ROOT, "src", "assets", "images")
OUT_SDL2 = os.path.join(ROOT, "engine", "platform", "cinema_cg_sdl2.h")
OUT_ROM = os.path.join(ROOT, "engine", "platform", "cinema_cg_rom.h")
OUT_SNES_ASM = os.path.join(ROOT, "engine", "platform", "cinema_cg_snes.asm")

PLATES = [
    ("ALDERBROOK_DUSK",    "cinema_alderbrook_dusk_1795309262024.jpg"),
    ("HOLLOW_OAK_CHASE",   "cinema_hollow_oak_chase_1795309261000.jpg"),
    ("EVERTALE_PANORAMA",  "cinema_evertale_panorama_1795309261863.jpg"),
    ("SHADOW_GRANDMA",     "cinema_shadow_grandma_1795309261174.jpg"),
    ("BEDROOM_COMFORT",    "cinema_bedroom_comfort_v2_1795309287400.jpg"),
    ("PIP_WINDOW",         "cinema_pip_window_1795309260734.jpg"),
]

SDL_W, SDL_H = 340, 156
ROM_W, ROM_H = 256, 120   # 32 x 15 tiles of 8x8 = 480 map entries
MAX_ROM_TILES = 340       # Comfortably fits in SNES BG1 VRAM (64..403) & < 12KB per LoROM bank
SNES_CG_TILE_BASE = 64    # Matches VRAM_CG_TILE_BASE in engine/platform/snes_main.c


def read_ppm(path, w, h, quantize_15=False):
    cmd = ["convert", path, "-resize", f"{w}x{h}^", "-gravity", "center", "-extent", f"{w}x{h}"]
    if quantize_15:
        cmd += ["-dither", "FloydSteinberg", "-colors", "15"]
    cmd += ["-depth", "8", "rgb:-"]
    raw = subprocess.check_output(cmd)
    assert len(raw) == w * h * 3, f"Expected {w*h*3} bytes, got {len(raw)}"
    return raw


def rgb888_to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def rgb888_to_bgr555(r, g, b):
    return ((b >> 3) << 10) | ((g >> 3) << 5) | (r >> 3)


def rgb888_to_bgr333(r, g, b):
    return (((b >> 5) & 7) << 9) | (((g >> 5) & 7) << 5) | (((r >> 5) & 7) << 1)


def build_sdl2_header():
    print(f"Baking {len(PLATES)} RGB565 plates ({SDL_W}x{SDL_H}) -> {OUT_SDL2}")
    with open(OUT_SDL2, "w") as f:
        f.write("/* Auto-generated by engine/tools/bake_cinema_cg.py — DO NOT EDIT */\n")
        f.write("#ifndef HEARTH_CINEMA_CG_SDL2_H\n#define HEARTH_CINEMA_CG_SDL2_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define CINEMA_SDL_PLATE_COUNT {len(PLATES)}\n")
        f.write(f"#define CINEMA_SDL_W {SDL_W}\n")
        f.write(f"#define CINEMA_SDL_H {SDL_H}\n\n")
        f.write(f"static const uint16_t CINEMA_SDL_PLATES[{len(PLATES)}][{SDL_W * SDL_H}] = {{\n")
        for idx, (name, fname) in enumerate(PLATES):
            raw = read_ppm(os.path.join(IMG_DIR, fname), SDL_W, SDL_H, quantize_15=False)
            f.write(f"    /* {idx}: {name} */\n    {{\n")
            vals = []
            for i in range(0, len(raw), 3):
                vals.append(rgb888_to_rgb565(raw[i], raw[i + 1], raw[i + 2]))
            for row in range(0, len(vals), 16):
                chunk = vals[row:row + 16]
                f.write("        " + ",".join(f"0x{v:04X}" for v in chunk) + ",\n")
            f.write("    },\n")
        f.write("};\n\n#endif /* HEARTH_CINEMA_CG_SDL2_H */\n")


def extract_tile_indexed(indexed, w, tx, ty):
    tile = bytearray(64)
    k = 0
    for py in range(8):
        row_off = (ty * 8 + py) * w + tx * 8
        for px in range(8):
            tile[k] = indexed[row_off + px]
            k += 1
    return bytes(tile)


def tile_error(t1, t2, pal):
    err = 0
    for i in range(64):
        c1 = pal[t1[i]]
        c2 = pal[t2[i]]
        dr = c1[0] - c2[0]
        dg = c1[1] - c2[1]
        db = c1[2] - c2[2]
        err += dr * dr + dg * dg + db * db
    return err


def pack_genesis_tile(tile_64):
    """8x8 4bpp packed nibbles -> 32 bytes (big-endian u32 rows for SGDK)."""
    out = bytearray(32)
    for y in range(8):
        for x in range(0, 8, 2):
            p0 = tile_64[y * 8 + x] & 0x0F
            p1 = tile_64[y * 8 + x + 1] & 0x0F
            out[y * 4 + (x >> 1)] = (p0 << 4) | p1
    return out


def pack_snes_tile(tile_64):
    """8x8 4bpp planar -> 32 bytes (planes 0/1 interleaved first 16B, planes 2/3 next 16B)."""
    out = bytearray(32)
    for y in range(8):
        bp0 = bp1 = bp2 = bp3 = 0
        for x in range(8):
            c = tile_64[y * 8 + x] & 0x0F
            bit = 7 - x
            if c & 1: bp0 |= (1 << bit)
            if c & 2: bp1 |= (1 << bit)
            if c & 4: bp2 |= (1 << bit)
            if c & 8: bp3 |= (1 << bit)
        out[y * 2 + 0] = bp0
        out[y * 2 + 1] = bp1
        out[16 + y * 2 + 0] = bp2
        out[16 + y * 2 + 1] = bp3
    return out


def quantize_plate_to_tiles(raw):
    # Collect unique palette colors (index 0 reserved for matte black #0B0D14)
    pal = [(11, 13, 20)]
    color_map = {}
    indexed = bytearray(ROM_W * ROM_H)
    for i in range(ROM_W * ROM_H):
        rgb = (raw[i * 3], raw[i * 3 + 1], raw[i * 3 + 2])
        idx = color_map.get(rgb)
        if idx is None:
            if len(pal) < 16:
                idx = len(pal)
                pal.append(rgb)
                color_map[rgb] = idx
            else:
                # Nearest existing palette color
                best_i = 1
                best_d = 1 << 30
                for pi in range(1, len(pal)):
                    pr, pg, pb = pal[pi]
                    d = (rgb[0] - pr) ** 2 + (rgb[1] - pg) ** 2 + (rgb[2] - pb) ** 2
                    if d < best_d:
                        best_d = d
                        best_i = pi
                idx = best_i
                color_map[rgb] = idx
        indexed[i] = idx
    while len(pal) < 16:
        pal.append((11, 13, 20))

    # Extract 32x15 = 480 tiles and deduplicate exact matches first
    tw, th = ROM_W // 8, ROM_H // 8
    unique_tiles = []
    tile_dict = {}
    tilemap = []
    for ty in range(th):
        for tx in range(tw):
            t = extract_tile_indexed(indexed, ROM_W, tx, ty)
            tid = tile_dict.get(t)
            if tid is None:
                tid = len(unique_tiles)
                unique_tiles.append(t)
                tile_dict[t] = tid
            tilemap.append(tid)

    # If > MAX_ROM_TILES, merge closest perceptual tile pairs via sorted-signature window + union-find
    if len(unique_tiles) > MAX_ROM_TILES:
        def tile_key(t):
            r = g = b = 0
            for c in t:
                pr, pg, pb = pal[c]
                r += pr; g += pg; b += pb
            lum = (r * 3 + g * 6 + b) // 10
            return (lum, r, g, b)

        n = len(unique_tiles)
        order = sorted(range(n), key=lambda idx: tile_key(unique_tiles[idx]))
        # Precompute candidate pairs across a generous +/-28 luminance window
        pairs = []
        win = 28
        for pos in range(n):
            a = order[pos]
            ta = unique_tiles[a]
            end_pos = min(n, pos + 1 + win)
            for pos2 in range(pos + 1, end_pos):
                b = order[pos2]
                err = tile_error(ta, unique_tiles[b], pal)
                pairs.append((err, a, b))
        pairs.sort(key=lambda x: x[0])

        parent = list(range(n))
        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        remaining = n
        for _err, a, b in pairs:
            if remaining <= MAX_ROM_TILES:
                break
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[rb] = ra
                remaining -= 1

        # Fallback sweep if window left slightly more than MAX_ROM_TILES
        if remaining > MAX_ROM_TILES:
            roots = [i for i in range(n) if find(i) == i]
            roots.sort(key=lambda idx: tile_key(unique_tiles[idx]))
            for k in range(0, len(roots) - 1, 2):
                if remaining <= MAX_ROM_TILES:
                    break
                parent[roots[k + 1]] = roots[k]
                remaining -= 1

        # Compact indices to 0..remaining-1
        active = sorted({find(i) for i in range(n)})
        new_id = {old: idx for idx, old in enumerate(active)}
        unique_tiles = [unique_tiles[old] for old in active]
        tilemap = [new_id[find(tid)] for tid in tilemap]

    return pal, unique_tiles, tilemap


def build_rom_header():
    print(f"Baking {len(PLATES)} quantized 16-color ROM plates ({ROM_W}x{ROM_H}, max {MAX_ROM_TILES} tiles)")
    print(f"  -> {OUT_ROM} (Genesis C header + SNES extern declarations)")
    print(f"  -> {OUT_SNES_ASM} (SNES WLA-DX per-plate SUPERFREE LoROM banks)")

    baked = []
    for idx, (name, fname) in enumerate(PLATES):
        raw = read_ppm(os.path.join(IMG_DIR, fname), ROM_W, ROM_H, quantize_15=True)
        pal, tiles, tilemap = quantize_plate_to_tiles(raw)
        pal_snes = [rgb888_to_bgr555(*c) for c in pal]
        pal_gen = [rgb888_to_bgr333(*c) for c in pal]
        baked.append((idx, name, tiles, tilemap, pal_snes, pal_gen))
        print(f"  Plate {idx} ({name}): {len(tiles)} unique tiles ({len(tiles)*32} bytes)")

    # 1. Write C header: tiny metadata + externs on SNES; full 4bpp arrays on Genesis
    with open(OUT_ROM, "w") as f:
        f.write("/* Auto-generated by engine/tools/bake_cinema_cg.py — DO NOT EDIT */\n")
        f.write("/* Strict ANSI C89 safe for both Sega Genesis (SGDK) and SNES (816-tcc LoROM) */\n")
        f.write("#ifndef HEARTH_CINEMA_CG_ROM_H\n#define HEARTH_CINEMA_CG_ROM_H\n\n")
        f.write("#include \"hearth_types.h\"\n\n")
        f.write(f"#define CINEMA_ROM_PLATE_COUNT {len(PLATES)}\n")
        f.write(f"#define CINEMA_ROM_TW {ROM_W // 8}\n")
        f.write(f"#define CINEMA_ROM_TH {ROM_H // 8}\n")
        f.write(f"#define CINEMA_ROM_MAP_LEN {(ROM_W // 8) * (ROM_H // 8)}\n\n")

        f.write("static const uint16_t CINEMA_ROM_TILE_COUNTS[CINEMA_ROM_PLATE_COUNT] = {\n    ")
        f.write(", ".join(f"{len(b[2])}u" for b in baked))
        f.write("\n};\n\n")

        f.write("#if defined(HEARTH_TARGET_SNES)\n")
        f.write("/* SNES places each 11.9KB plate in its own SUPERFREE LoROM bank (cinema_cg_snes.asm) */\n")
        for idx, name, _tiles, _tilemap, _ps, _pg in baked:
            f.write(f"extern char cg_plate{idx}_tiles, cg_plate{idx}_map, cg_plate{idx}_pal; /* {name} */\n")
        f.write("#else\n\n")

        for idx, name, tiles, tilemap, _ps, _pg in baked:
            f.write(f"/* Plate {idx}: {name} */\n")
            f.write(f"static const uint16_t CINEMA_ROM_MAP_{idx}[CINEMA_ROM_MAP_LEN] = {{\n")
            for r in range(0, len(tilemap), 16):
                f.write("    " + ",".join(f"{v}u" for v in tilemap[r:r + 16]) + ",\n")
            f.write("};\n\n")

            f.write(f"static const uint32_t CINEMA_GEN_TILES_{idx}[{len(tiles) * 8}] = {{\n")
            for t in tiles:
                packed = pack_genesis_tile(t)
                u32s = struct.unpack(">8I", packed)
                f.write("    " + ",".join(f"0x{v:08X}u" for v in u32s) + ",\n")
            f.write("};\n\n")

        f.write("static const uint16_t CINEMA_ROM_PALS[CINEMA_ROM_PLATE_COUNT][16] = {\n")
        for _idx, _name, _tiles, _tilemap, _ps, pal_gen in baked:
            f.write("    {" + ",".join(f"0x{v:04X}u" for v in pal_gen) + "},\n")
        f.write("};\n")
        f.write("static const uint32_t * const CINEMA_GEN_TILE_PTRS[CINEMA_ROM_PLATE_COUNT] = {\n")
        for idx in range(len(PLATES)):
            f.write(f"    CINEMA_GEN_TILES_{idx},\n")
        f.write("};\n")
        f.write("static const uint16_t * const CINEMA_ROM_MAP_PTRS[CINEMA_ROM_PLATE_COUNT] = {\n")
        for idx in range(len(PLATES)):
            f.write(f"    CINEMA_ROM_MAP_{idx},\n")
        f.write("};\n")
        f.write("#endif /* HEARTH_TARGET_SNES */\n\n")
        f.write("#endif /* HEARTH_CINEMA_CG_ROM_H */\n")

    # 2. Write WLA-DX assembly file for SNES (each plate in its own ~11.9KB SUPERFREE section)
    with open(OUT_SNES_ASM, "w") as f:
        f.write("; Auto-generated by engine/tools/bake_cinema_cg.py — DO NOT EDIT\n")
        f.write("; Places each SNES 4bpp Cinema CG plate (~11.9 KB) in its own SUPERFREE LoROM section\n")
        f.write("; so Bank 0 .rodata stays tiny and wlalink packs all 6 plates across 32 ROM banks.\n\n")
        f.write('.include "hdr.asm"\n\n')
        for idx, name, tiles, tilemap, pal_snes, _pg in baked:
            f.write(f'; --- Plate {idx}: {name} ({len(tiles)} tiles, {len(tiles)*32 + len(tilemap)*2 + 32} bytes) ---\n')
            f.write(f'.section ".rodata_cg{idx}" superfree\n\n')
            f.write(f'cg_plate{idx}_tiles:\n')
            for t in tiles:
                packed = pack_snes_tile(t)
                f.write('.db ' + ','.join(f'${b:02X}' for b in packed[:16]) + '\n')
                f.write('.db ' + ','.join(f'${b:02X}' for b in packed[16:]) + '\n')
            f.write(f'\ncg_plate{idx}_map:\n')
            for r in range(0, len(tilemap), 8):
                chunk = tilemap[r:r + 8]
                # Pre-encoded SNES BG1 tilemap entries: VRAM_CG_TILE_BASE + tid, pal 0, prio 0
                f.write('.dw ' + ','.join(f'${(SNES_CG_TILE_BASE + v) & 0x03FF:04X}' for v in chunk) + '\n')
            f.write(f'\ncg_plate{idx}_pal:\n')
            f.write('.dw ' + ','.join(f'${v:04X}' for v in pal_snes[:8]) + '\n')
            f.write('.dw ' + ','.join(f'${v:04X}' for v in pal_snes[8:]) + '\n')
            f.write('.ends\n\n')


if __name__ == "__main__":
    if "--rom-only" not in sys.argv:
        build_sdl2_header()
    build_rom_header()
    print("Done baking all cinema CG assets!")
