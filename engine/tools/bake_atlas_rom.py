#!/usr/bin/env python3
"""
Pre-bakes the deduplicated 192x128 (24x16 tile) 4bpp Evertale World Atlas
for Sega Genesis into engine/platform/atlas_gen_rom.h.

Eliminates ~750ms of runtime 68000 pixel baking on Atlas open and shrinks the
Atlas VRAM footprint from 384 tiles to ~138 tiles so it coexists disjointly
with the 163-tile Alpine Parallax Vista inside the 480-tile shared block!
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA_C = os.path.join(ROOT, "engine", "core", "hearth_data.c")
OUT_H = os.path.join(ROOT, "engine", "platform", "atlas_gen_rom.h")


def parse_globe_data():
    src = open(DATA_C, "r").read()
    m = re.search(
        r"GLOBE_MACRO_ROWS\[HEARTH_ATLAS_H\]\[HEARTH_ATLAS_W \+ 1\]\s*=\s*\{(.*?)\};",
        src,
        re.S,
    )
    if not m:
        raise RuntimeError("Could not find GLOBE_MACRO_ROWS in hearth_data.c")
    rows = re.findall(r'"([^"]+)"', m.group(1))
    assert len(rows) == 48 and all(len(r) == 64 for r in rows), "Expected 64x48 GLOBE_MACRO_ROWS"

    lm_m = re.search(
        r"HEARTH_GLOBE_LANDMARKS\[HEARTH_GLOBE_LANDMARK_COUNT\]\s*=\s*\{(.*?)\};",
        src,
        re.S,
    )
    if not lm_m:
        raise RuntimeError("Could not find HEARTH_GLOBE_LANDMARKS in hearth_data.c")
    lms = []
    for line in lm_m.group(1).splitlines():
        mm = re.search(r"\{\s*(\d+)u?,\s*(\d+)u?,.*?,\s*(\d+)u?,\s*\"", line)
        if mm:
            tx, ty, enterable = int(mm.group(1)), int(mm.group(2)), int(mm.group(3))
            lms.append(((tx * 3) >> 2, (ty * 171) >> 8, 13 if enterable else 14))
    assert len(lms) == 14, f"Expected 14 landmarks, got {len(lms)}"
    return rows, lms


def atlas_cell(rows, ax, ay):
    c = rows[ay % 48][ax & 63]
    if c == "~":
        return 0
    if c == "s":
        return 1
    if c == "r":
        return 2
    if c in "ghfm":
        return 3
    if c in "do":
        return 4
    if c in "pb":
        return 5
    if c in "iI":
        return 6
    if c in "jJ":
        return 7
    if c in "vVl":
        return 8
    if c in "tT":
        return 9
    return 0


def bake():
    rows, lms = parse_globe_data()
    px_ax = [min(px // 3, 63) for px in range(192)]
    px_mod3 = [px % 3 for px in range(192)]
    px_grat = [1 if (px % 24) == 0 else 0 for px in range(192)]

    uniq = {}
    tiles = []
    tmap = []

    for ty in range(16):
        ay0 = ty * 3
        ay_next = min(ay0 + 3, 47)
        r3 = [[atlas_cell(rows, ax, ay0 + s) for ax in range(64)] for s in range(3)]
        bel = [atlas_cell(rows, ax, ay_next) for ax in range(64)]
        for tx in range(24):
            tx0, ty0 = tx * 8, ty * 8
            words = []
            for ly in range(8):
                py = ty0 + ly
                sub = 0 if ly < 3 else (1 if ly < 5 else 2)
                py_grat = 1 if py in (0, 24, 48, 72, 96, 120) else 0
                py_even = 1 if (py & 1) == 0 else 0
                is_row_seam = 1 if ly in (3, 5) else 0
                w = 0
                for lx in range(8):
                    px = tx0 + lx
                    ax = px_ax[px]
                    cell = r3[sub][ax]
                    col = (cell if cell < 10 else 0) + 2
                    if cell == 0 and ((px_grat[px] and py_even) or (py_grat and ((px & 1) == 0))):
                        col = 15
                    if cell < 3:
                        if is_row_seam and sub > 0 and r3[sub - 1][ax] >= 3:
                            col = 1
                        elif px_mod3[px] == 0 and ax > 0 and r3[sub][ax - 1] >= 3:
                            col = 1
                    elif ly == 7 and bel[ax] < 3:
                        col = 1
                    for lpx, lpy, lcol in lms:
                        dx, dy = px - lpx, py - lpy
                        if -2 <= dx <= 2 and -2 <= dy <= 2:
                            if -1 <= dx <= 1 and -1 <= dy <= 1:
                                col = lcol
                            elif (dx not in (-2, 2)) or (dy not in (-2, 2)):
                                col = 1
                    if px in (0, 191) or py in (0, 127):
                        col = 12
                    w = (w << 4) | (col & 0x0F)
                words.append(w)
            key = tuple(words)
            if key not in uniq:
                uniq[key] = len(tiles)
                tiles.append(words)
            tmap.append(uniq[key])

    assert len(tiles) <= 255, f"Atlas tile count {len(tiles)} exceeds u8 map / 288-tile budget"

    lines = [
        "/* Auto-generated by engine/tools/bake_atlas_rom.py — DO NOT EDIT */",
        "/* Deduplicated 192x128 (24x16) 4bpp Evertale World Atlas for Sega Genesis ROM */",
        "#ifndef HEARTH_ATLAS_GEN_ROM_H",
        "#define HEARTH_ATLAS_GEN_ROM_H",
        "",
        f"#define GEN_ATLAS_TILE_COUNT {len(tiles)}u",
        "",
        f"static const u32 GEN_ATLAS_TILES[{len(tiles) * 8}u] = {{",
    ]
    for i, w8 in enumerate(tiles):
        sep = "," if i + 1 < len(tiles) else ""
        row_str = ", ".join(f"0x{w:08X}u" for w in w8)
        lines.append(f"    {row_str}{sep}")
    lines.append("};")
    lines.append("")
    lines.append("static const u8 GEN_ATLAS_MAP[384u] = {")
    for r in range(16):
        chunk = tmap[r * 24 : (r + 1) * 24]
        sep = "," if r < 15 else ""
        lines.append("    " + ", ".join(f"{v:3d}u" for v in chunk) + sep)
    lines.append("};")
    lines.append("")
    lines.append("#endif /* HEARTH_ATLAS_GEN_ROM_H */")
    lines.append("")

    with open(OUT_H, "w") as f:
        f.write("\n".join(lines))
    print(f"[OK] Baked Genesis World Atlas ROM: {len(tiles)} unique tiles ({len(tiles)*32} B) + 384B map -> {OUT_H}")


if __name__ == "__main__":
    bake()
