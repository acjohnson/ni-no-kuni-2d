/* ============================================================================
 * bake_rowan_rom.c — Single-Source-of-Truth Pre-Baker for 16x24 Rowan Sprites
 *
 * Reads all 33 unique Rowan 16x24 poses directly from engine/platform/hearth_hero24.h
 * and emits zero-CPU, DMA-ready ROM tile tables:
 *   1. engine/platform/rowan_snes_rom.asm (6,336 B 4bpp SNES planar in SUPERFREE bank)
 *   2. engine/platform/rowan_gen_rom.h    (6,336 B 4bpp Genesis column-major const u32)
 *
 * Pose Index Layout (0..32):
 *   0..27  : Explore poses (dir * 7 + pose), dir=0..3 (D/U/L/R), pose=0..6
 *   28..32 : Battle poses (28 + (pose - 7)), pose=7..11 (always DIR_RIGHT)
 *
 * Build & Run:
 *   cc -std=c99 -O2 -Iengine/core engine/tools/bake_rowan_rom.c -o /tmp/bake_rowan_rom
 *   /tmp/bake_rowan_rom
 * ============================================================================ */

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "hearth_types.h"

void hearth_memset(void *dst, uint8_t val, uint16_t len) {
    memset(dst, (int)val, (size_t)len);
}

#include "../platform/hearth_hero24.h"

/* Suppress unused-function warnings for helper bakers not needed by Rowan ROM baker */
static void suppress_unused_bakers(void) {
    (void)hearth_bake_pip_16x16;
    (void)hearth_bake_npc_16x24;
}

static void encode_snes_4bpp_tile(const uint8_t *src384, uint8_t ox, uint8_t oy, uint8_t dst32[32]) {
    uint8_t y, x;
    for (y = 0u; y < 8u; y++) {
        uint8_t bp0 = 0u, bp1 = 0u, bp2 = 0u, bp3 = 0u;
        for (x = 0u; x < 8u; x++) {
            uint8_t mask = (uint8_t)(0x80u >> x);
            uint8_t c = src384[(uint16_t)(oy + y) * 16u + (uint16_t)(ox + x)] & 0x0Fu;
            if (c & 1u) bp0 |= mask;
            if (c & 2u) bp1 |= mask;
            if (c & 4u) bp2 |= mask;
            if (c & 8u) bp3 |= mask;
        }
        dst32[y * 2u]        = bp0;
        dst32[y * 2u + 1u]   = bp1;
        dst32[16u + y * 2u]  = bp2;
        dst32[17u + y * 2u]  = bp3;
    }
}

static void encode_gen_16x24(const uint8_t *src384, uint32_t dst48[48]) {
    static const uint8_t ox[6] = { 0u, 0u, 0u, 8u, 8u, 8u };
    static const uint8_t oy[6] = { 0u, 8u, 16u, 0u, 8u, 16u };
    uint16_t t, y, x;
    for (t = 0u; t < 6u; t++) {
        for (y = 0u; y < 8u; y++) {
            uint32_t row = 0u;
            for (x = 0u; x < 8u; x++) {
                uint8_t c = src384[(uint16_t)(oy[t] + y) * 16u + (uint16_t)(ox[t] + x)] & 0x0Fu;
                row = (row << 4) | (uint32_t)c;
            }
            dst48[t * 8u + y] = row;
        }
    }
}

int main(void) {
    static const uint8_t snes_ox[6] = { 0u, 8u, 0u, 8u, 0u, 8u };
    static const uint8_t snes_oy[6] = { 0u, 0u, 8u, 8u, 16u, 16u };
    uint8_t pix24[384];
    uint8_t snes_pose[6][32];
    uint32_t gen_pose[48];
    FILE *fsnes, *fgen;
    uint8_t idx, dir, pose, t;
    int i;

    (void)suppress_unused_bakers;

    fsnes = fopen("engine/platform/rowan_snes_rom.asm", "wb");
    fgen  = fopen("engine/platform/rowan_gen_rom.h", "wb");
    if (!fsnes || !fgen) {
        fprintf(stderr, "bake_rowan_rom: failed to open output files\n");
        return 1;
    }

    fprintf(fsnes,
        "; Auto-generated by engine/tools/bake_rowan_rom.c — DO NOT EDIT\n"
        "; Pre-baked 4bpp SNES planar tiles for all 33 unique 16x24 Rowan poses (6,336 bytes)\n"
        "; Zero 65816 runtime CPU baking — streamed directly from ROM during VBlank DMA!\n\n"
        ".section \".rodata_rowan\" superfree\n\n"
        "rowan_snes_tiles:\n");

    fprintf(fgen,
        "/* Auto-generated by engine/tools/bake_rowan_rom.c — DO NOT EDIT\n"
        " * Pre-baked 4bpp Genesis column-major tiles for all 33 unique 16x24 Rowan poses (6,336 bytes)\n"
        " * Zero 68000 runtime CPU baking — passed directly to VDP_loadTileData(..., DMA_QUEUE)! */\n\n"
        "#ifndef ROWAN_GEN_ROM_H\n"
        "#define ROWAN_GEN_ROM_H\n\n"
        "#define ROWAN_ROM_POSE_COUNT 33u\n\n"
        "static const u32 ROWAN_GEN_TILES[ROWAN_ROM_POSE_COUNT][48] = {\n");

    for (idx = 0u; idx < 33u; idx++) {
        if (idx < 28u) {
            dir  = (uint8_t)(idx / 7u);
            pose = (uint8_t)(idx % 7u);
        } else {
            dir  = (uint8_t)DIR_RIGHT;
            pose = (uint8_t)(HERO_POSE_BTL_READY + (idx - 28u));
        }

        hearth_bake_rowan_16x24(pix24, dir, pose);

        /* 1. SNES 4bpp planar: [TL, TR, ML, MR, BL, BR] (192 bytes) */
        fprintf(fsnes, "; Pose %2u (dir=%u, pose=%u)\n", (unsigned)idx, (unsigned)dir, (unsigned)pose);
        for (t = 0u; t < 6u; t++) {
            encode_snes_4bpp_tile(pix24, snes_ox[t], snes_oy[t], snes_pose[t]);
            for (i = 0; i < 32; i += 16) {
                int k;
                fprintf(fsnes, ".db ");
                for (k = 0; k < 16; k++) {
                    fprintf(fsnes, "%s$%02X", (k == 0) ? "" : ",", (unsigned)snes_pose[t][i + k]);
                }
                fprintf(fsnes, "\n");
            }
        }

        /* 2. Genesis 4bpp column-major: 6 tiles x 8 u32 rows = 48 u32s */
        encode_gen_16x24(pix24, gen_pose);
        fprintf(fgen, "    { /* Pose %2u (dir=%u, pose=%u) */\n", (unsigned)idx, (unsigned)dir, (unsigned)pose);
        for (i = 0; i < 48; i += 6) {
            int k;
            fprintf(fgen, "        ");
            for (k = 0; k < 6; k++) {
                fprintf(fgen, "0x%08Xu%s", (unsigned)gen_pose[i + k], (i + k == 47) ? "" : ", ");
            }
            fprintf(fgen, "\n");
        }
        fprintf(fgen, "    }%s\n", (idx == 32u) ? "" : ",");
    }

    fprintf(fsnes, ".ends\n");
    fprintf(fgen, "};\n\n#endif /* ROWAN_GEN_ROM_H */\n");

    fclose(fsnes);
    fclose(fgen);
    printf("Generated engine/platform/rowan_snes_rom.asm (6336 bytes) and engine/platform/rowan_gen_rom.h (6336 bytes)\n");
    return 0;
}
